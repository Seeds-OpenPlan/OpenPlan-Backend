--
-- 🔴 삭제 전파의 안전 가드가 이름으로는 성립하지 않는다 (2026-08-29 리뷰 Blocking).
--
--    원격 삭제를 판정할 때 "이번에 조회한 캘린더인가" 를 확인해야 한다 — 선택 해제한
--    캘린더는 조회조차 하지 않았으므로 "안 왔다" 가 "지워졌다" 를 뜻하지 않는다.
--    그 판정을 **표시 이름**(source_calendar)으로 하고 있었는데, 이름은 유일하지 않다:
--    선택의 유일성 제약은 external_calendar_id 기준이다(ux_ext_selection).
--
--    그래서 같은 연동에 이름이 같은 캘린더 둘이 있고 그중 하나만 선택 해제하면,
--    **조회하지도 않은 캘린더의 일정이 "선택된 것" 으로 오판돼 지워진다.** 가드가
--    막겠다고 선언한 바로 그 경우가 이름 충돌 앞에서 뚫린다.
--
--    id 는 제공자가 보장하는 식별자다(구글 calendarId · 애플 캘린더 href).
--
-- 기존 행: NULL 로 시작한다. 채워질 때까지 그 행들은 **삭제 대상에서 제외**된다 —
--    귀속을 못 하면 지우지 않는다(모르면 남긴다). 다음 동기화가 값을 채운다.
-- =====================================================================================

ALTER TABLE external_calendar_events
    ADD COLUMN external_calendar_id VARCHAR(512);

COMMENT ON COLUMN external_calendar_events.external_calendar_id IS
    '이 일정이 온 제공자 캘린더 식별자(구글 calendarId · 애플 href). 표시 이름과 달리 유일하다 — 삭제 전파의 귀속 판정에 쓴다.';
