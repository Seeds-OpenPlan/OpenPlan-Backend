-- refresh 회전으로 소진된 시각.
--
-- 왜 필요한가: 재사용 탐지가 "정상 클라이언트의 중복 갱신"과 "탈취"를 구분하지 못했다.
-- 회전은 서버에서 커밋된 뒤 Set-Cookie 가 브라우저에 닿기까지 수백 ms 가 걸리는데, 그 창에
-- 출발한 두 번째 갱신은 헌 토큰을 들고 온다. 지금까지 그것을 탈취로 보고 해당 사용자의
-- 활성 세션을 전부 폐기했고, 그래서 액세스 토큰 수명(30분)마다 로그인이 풀렸다.
--
-- 이 컬럼이 있으면 "언제 소진됐는가" 를 물을 수 있고, 회전 직후의 중복은 폐기 없이 401 로만
-- 끝낼 수 있다. 유예창 밖의 재사용은 종전대로 전 세션 폐기다.
--
-- 기존 행은 NULL 로 남는다 — 회전 시각을 모르는 세션이므로 유예 대상이 아니고, 그 편이 안전하다.
ALTER TABLE auth_sessions ADD COLUMN rotated_at TIMESTAMPTZ;

COMMENT ON COLUMN auth_sessions.rotated_at IS
    '회전으로 소진된 시각. 재사용 탐지에서 정상 클라이언트의 중복 갱신과 탈취를 가르는 기준. 소진되지 않은 세션은 NULL.';
