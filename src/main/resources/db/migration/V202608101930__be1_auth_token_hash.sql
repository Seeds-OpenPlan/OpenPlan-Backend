-- =====================================================================================
-- ST-B1-04/05 — auth_tokens 토큰 해시 컬럼 (BE-1)
--
-- 배경: V1 baseline 은 ERD 를 그대로 따라 auth_tokens 에 **토큰 값을 담을 자리를 두지 않았다**.
--       그래서 현 구조로 링크를 만들면 token_id(UUID) 를 그대로 실어야 하고, 그것은 곧
--       **DB 를 읽을 수 있는 사람이 유효한 인증·재설정 링크를 그대로 손에 넣는다**는 뜻이다.
--       be1-notes 가 "ST-B1-04/05 착수 시 재검토 대상"으로 남겨 둔 항목이며, 지금이 그 시점이다.
--
-- 결정: 링크에는 **불투명 난수 원문**을 싣고 서버에는 **SHA-256 해시만** 저장한다.
--       refresh 토큰(auth_sessions.refresh_token_hash)과 같은 방식·같은 이유다 —
--       원문을 저장하지 않으면 DB 유출이 곧 계정 탈취가 되지 않는다.
--
-- BCrypt 가 아니라 SHA-256 인 이유: 조회가 해시 일치로 이뤄져야 하는데(UNIQUE 인덱스 탐색)
--       BCrypt 는 salt 때문에 "값으로 찾기"가 성립하지 않는다. 비밀번호와 달리 이 토큰은
--       고엔트로피 난수라 사전공격 대상이 아니므로 느린 해시가 필요 없다.
--
-- NOT NULL 로 거는 근거: 이 테이블에는 **쓰는 코드가 없어 행이 존재하지 않는다**
--       (엔티티·리포지토리 0건, dev 시드 0행 — 착수 전 실측). 나중에 nullable 로 두면
--       해시 없이 저장된 토큰이 조용히 쓸모없어지는 경로가 남는다.
-- =====================================================================================

ALTER TABLE auth_tokens
    ADD COLUMN token_hash VARCHAR(255) NOT NULL;

COMMENT ON COLUMN auth_tokens.token_hash IS
    '링크에 실린 원문 토큰의 SHA-256 해시. 원문은 저장하지 않는다 (NFR-005 1회용은 used_at·status 가 보장).';

-- 링크 검증의 유일한 조회 경로. UNIQUE 는 중복 발급 방지도 겸한다.
CREATE UNIQUE INDEX ux_auth_tokens_hash ON auth_tokens (token_hash);
