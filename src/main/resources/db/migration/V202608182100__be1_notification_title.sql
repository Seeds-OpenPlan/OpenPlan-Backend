-- 알림 title 스냅샷 컬럼 (ST-B1-12 · NOTI-02/04 · ADR-0014)
--
-- 정본 openapi 의 Notification 스키마는 title 을 요구하는데 V1 baseline 에 그 컬럼이 없었다.
-- ADR-0014 §"title 문구"가 "생성 시점 스냅샷으로 박제(이후 상태 변동 미반영 — createdAt
-- 시점의 사실)"로 정했으므로, 조회 시점에 조립하면 안 된다:
--   · '{태스크}' 마감이 {n}일 남았습니다 — n 은 날이 갈수록 달라진다
--   · 태스크 제목이 바뀌면 과거 알림의 문구까지 소급해 바뀐다
-- 둘 다 "그때 그런 일이 있었다"는 알림의 성격과 어긋난다. 그래서 컬럼으로 박제한다.
--
-- 길이 200: 카피에 들어가는 사용자 입력은 태스크 제목뿐이고 tasks.title 이 200 이다.
-- 말줄임은 애플리케이션이 하며(카피 표의 플레이스홀더 규칙), 여기서는 상한만 맞춘다.
--
-- 기존 행이 없으므로(알림 생성은 이 스토리에서 처음 구현된다) NOT NULL 을 바로 건다.
ALTER TABLE notifications ADD COLUMN title VARCHAR(200) NOT NULL;
