-- =====================================================================================
-- 이슈 #69 1단계 — 이 연동으로 밖에 쓸 수 있는가 (BE-1)
--
-- 구글 스코프를 calendar.readonly → calendar.events 로 넓힌다. 🔴 그런데 **이미 연동한
-- 사용자의 토큰은 옛 스코프로 발급된 것**이다. 그 토큰으로 쓰기를 시도하면 구글이
-- 403 insufficient scope 를 준다 — 사용자는 "연동돼 있는데 왜 안 되지" 만 보게 된다.
--
-- 코드만 바꿔서는 구분할 방법이 없다. 그래서 **제공자가 실제로 부여한 스코프**를 토큰
-- 교환·갱신 응답에서 받아 여기 적어 둔다. 쓰기 전에 이 값을 보고 판단한다.
--
-- 🔴 기존 행은 NULL 로 남는다. NULL = 모름이고, **모르면 쓰지 않는다** — 이 저장소가
--    삭제 귀속(#70)·반복 판정(#71)·쓰기 대상 캘린더(#76)에서 세 번 같은 결론에 닿은 원칙이다.
--    다음 재동의가 값을 채운다.
--
-- 애플(CalDAV)은 스코프 개념이 없다 — 앱 암호가 곧 전권이라 이 컬럼을 보지 않는다.
-- =====================================================================================
ALTER TABLE external_calendar_connections
    ADD COLUMN granted_scope TEXT;

COMMENT ON COLUMN external_calendar_connections.granted_scope IS
    '제공자가 실제로 부여한 스코프(공백 구분). 쓰기 가능 여부 판정에 쓴다. NULL = 모름 → 쓰지 않는다. 애플은 스코프가 없어 항상 NULL.';
